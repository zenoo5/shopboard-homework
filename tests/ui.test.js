// Exercise the real page, coordinator, and delegated handlers in a simulated DOM.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
import { CART_STORAGE_KEY } from '../.test-build/storage.js';

const html = await readFile(new URL('../index.html', import.meta.url), 'utf8');
let instance = 0;

// Mount the real HTML and entry module with a fresh browser-like environment.
async function mount(saved = null) {
  const dom = new JSDOM(html, { url: 'http://localhost/' });
  globalThis.document = dom.window.document;
  globalThis.localStorage = dom.window.localStorage;
  globalThis.Element = dom.window.Element;
  globalThis.HTMLElement = dom.window.HTMLElement;
  globalThis.HTMLButtonElement = dom.window.HTMLButtonElement;
  if (saved !== null) localStorage.setItem(CART_STORAGE_KEY, saved);
  await import(`../.test-build/main.js?test=${instance++}`);
  return dom;
}

// Change a control using the same event type generated by the browser.
function change(dom, selector, value, event = 'change') {
  const control = document.querySelector(selector);
  control.value = value;
  control.dispatchEvent(new dom.window.Event(event, { bubbles: true }));
}

test('4 and 11: repeated catalog changes preserve controls and one click adds exactly one item', async () => {
  const dom = await mount();
  try {
    for (let repeat = 0; repeat < 5; repeat++) {
      change(dom, '#search', 'PHANTOM', 'input');
      change(dom, '#category', 'Keyboards');
      change(dom, '#sort', 'price-asc');
    }
    assert.equal(document.querySelectorAll('#product-grid article').length, 2);
    assert.equal(
      document.querySelector('#product-grid article').dataset.productId,
      'phantom-mini',
    );
    assert.equal(document.querySelector('#search').value, 'PHANTOM');
    assert.equal(document.querySelector('#category').value, 'Keyboards');
    document.querySelector('#product-grid [data-action="add"]').click();
    assert.equal(document.querySelector('#cart-count').textContent, '1');
    assert.deepEqual(JSON.parse(localStorage.getItem(CART_STORAGE_KEY)), [
      { id: 'phantom-mini', quantity: 1 },
    ]);
    document.querySelector('#product-grid [data-action="add"]').click();
    assert.equal(document.querySelectorAll('#cart-items article').length, 1);
    assert.equal(document.querySelector('#cart-count').textContent, '2');
    assert.equal(document.querySelector('#cart-total').textContent, '$179.98');
  } finally {
    dom.window.close();
  }
});

test('5–9: cart buttons update count, totals, storage, and other entries immediately', async () => {
  const dom = await mount();
  try {
    document
      .querySelector('[data-id="phantom-k75"][data-action="add"]')
      .click();
    document
      .querySelector('[data-id="pulse-wireless"][data-action="add"]')
      .click();
    document
      .querySelector('[data-id="phantom-k75"][data-action="increase"]')
      .click();
    assert.equal(document.querySelector('#cart-count').textContent, '3');
    assert.equal(document.querySelector('#cart-total').textContent, '$329.97');
    document
      .querySelector('[data-id="phantom-k75"][data-action="decrease"]')
      .click();
    assert.equal(document.querySelector('#cart-total').textContent, '$199.98');
    document
      .querySelector('[data-id="phantom-k75"][data-action="decrease"]')
      .click();
    assert.equal(document.querySelector('#cart-count').textContent, '1');
    assert.equal(document.querySelector('#cart-total').textContent, '$69.99');
    document
      .querySelector('[data-id="phantom-k75"][data-action="add"]')
      .click();
    document
      .querySelector('[data-id="phantom-k75"][data-action="remove"]')
      .click();
    assert.deepEqual(JSON.parse(localStorage.getItem(CART_STORAGE_KEY)), [
      { id: 'pulse-wireless', quantity: 1 },
    ]);
    document.querySelector('#clear-cart').click();
    assert.equal(document.querySelector('#cart-count').textContent, '0');
    assert.equal(document.querySelector('#cart-total').textContent, '$0.00');
    assert.deepEqual(JSON.parse(localStorage.getItem(CART_STORAGE_KEY)), []);
    assert.ok(document.querySelector('#clear-cart').disabled);
    assert.match(document.querySelector('#cart-items').textContent, /empty/i);
  } finally {
    dom.window.close();
  }
});

test('10: a fresh application instance restores saved quantities and totals', async () => {
  const first = await mount();
  document.querySelector('[data-id="phantom-k75"][data-action="add"]').click();
  document.querySelector('[data-id="phantom-k75"][data-action="add"]').click();
  const saved = localStorage.getItem(CART_STORAGE_KEY);
  first.window.close();
  const second = await mount(saved);
  try {
    assert.equal(document.querySelector('#cart-count').textContent, '2');
    assert.equal(document.querySelector('#cart-total').textContent, '$259.98');
    assert.equal(document.querySelectorAll('#cart-items article').length, 1);
  } finally {
    second.window.close();
  }
});

test('empty results offer a reset that clears all catalog controls', async () => {
  const dom = await mount();
  try {
    change(dom, '#category', 'Mice');
    change(dom, '#sort', 'price-desc');
    change(dom, '#search', 'nothing-matches', 'input');
    assert.equal(document.querySelectorAll('#product-grid article').length, 0);
    document.querySelector('#reset-filters').click();
    assert.equal(document.querySelectorAll('#product-grid article').length, 12);
    assert.equal(document.querySelector('#search').value, '');
    assert.equal(document.querySelector('#category').value, 'all');
    assert.equal(document.querySelector('#sort').value, 'default');
  } finally {
    dom.window.close();
  }
});

test('corrupt saved data does not prevent rendering or adding to cart', async () => {
  const dom = await mount('{broken');
  try {
    assert.equal(document.querySelectorAll('#product-grid article').length, 12);
    assert.equal(document.querySelector('#cart-count').textContent, '0');
    document.querySelector('[data-action="add"]').click();
    assert.equal(document.querySelector('#cart-count').textContent, '1');
  } finally {
    dom.window.close();
  }
});

test('cart updates announce inside an open modal rather than its inert background', async () => {
  const dom = await mount();
  try {
    document.querySelector('[data-action="add"]').click();
    document.querySelector('#cart-dialog').setAttribute('open', '');
    document.querySelector('[data-action="increase"]').click();
    assert.match(
      document.querySelector('#cart-action-status').textContent,
      /2 in cart/,
    );
    assert.equal(document.querySelector('#action-status').textContent, '');
  } finally {
    dom.window.close();
  }
});
